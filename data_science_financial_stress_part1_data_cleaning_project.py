def get_bank_financials_batch(cert_list, start_date="20100101", end_date="20261231", session=None):
    req = session if session else requests
    url = f"{base_url}/financials"

    # Combine all CERTs with OR, then add the date range with AND
    cert_part = " OR ".join(f"CERT:{c}" for c in cert_list)
    full_filter = f"({cert_part}) AND REPDTE:[{start_date} TO {end_date}]"

    params = {
        "filters": full_filter,
        "fields": "CERT,REPDTE,ASSET,DEP,ROA,NIMY,RBC1RWAJ,RBC1AAJ,NCLNLSR,NPERFV,LNATRESR,ENDEFYMD",
        "sort_by": "REPDTE",
        "sort_order": "ASC",
        "limit": 10000,
        "format": "json",
        "api_key": api_key
    }

    # Try up to 5 times if we get rate-limited
    for attempt in range(5):
        response = req.get(url, params=params, timeout=30)

        if response.status_code == 429:
            wait = 2 ** attempt  # waits 1, 2, 4, 8, 16 seconds
            print(f"Rate limited — waiting {wait} seconds...")
            time.sleep(wait)
            continue

        response.raise_for_status()
        result = response.json()

        if "data" not in result or not result["data"]:
            return pd.DataFrame()

        # Simple check: did we get everything, or did we hit the limit?
        total_available = result["meta"]["total"]
        total_returned = len(result["data"])
        if total_available > total_returned:
            print(f"WARNING: {total_available} records available, only got {total_returned}!")

        return pd.DataFrame([row["data"] for row in result["data"]])

    print("Gave up after 5 retries for this batch.")
    return pd.DataFrame()

